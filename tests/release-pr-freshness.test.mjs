async function git(cwd, ...args) {
  const { stdout } = await execFileAsync("git", args, { cwd, encoding: "utf8" });
  return stdout.trim();
}

function changeset(summary) {
  return '---\n"' + packageName + '": minor\n---\n\n' + summary + "\n";
}

function generatedRelease(version, summaries) {
  const entries = summaries
    .map(
      (summary, index) =>
        "- [#" +
        (index + 1) +
        "](https://example.invalid/pr/" +
        (index + 1) +
        ") - " +
        summary,
    )
    .join("\n\n");
  const heading = "## " + version;
  const changelogSection = heading + "\n\n### Minor Changes\n\n" + entries;
  return {
    changelog:
      "# " +
      packageName +
      "\n\n" +
      changelogSection +
      "\n\n## 1.0.0\n",
    body:
      "Generated by Changesets.\n\n# Releases\n" +
      changelogSection.replace(heading, "## " + packageName + "@" + version),
  };
}


import { readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";

const packageRoot = new URL("..", import.meta.url);
const output = new URL(
  "../src/consumer-integration/generated/canonical-assets.ts",
  import.meta.url
);
const [skillV1, skillV2, priorSkillV2, caller, transitionCatalog] = await Promise.all([
  readFile(new URL("../assets/history/sha256-7b31cd257532247f64c55a014dc926c601e4d742176cfb8513b6b0d8ab48213e/skill.md", import.meta.url), "utf8"),
  readFile(new URL("../skills/docs/SKILL.md", import.meta.url), "utf8"),
  readFile(new URL("../assets/history/sha256-641265ef9ecff59c16482fdae1bc8fc56002b5a4a1ee34b102438d0ca08a86a3/skill.md", import.meta.url), "utf8"),
  readFile(new URL("../assets/docs-protocol.yml", import.meta.url), "utf8"),
  readFile(new URL("../assets/transition-catalog.json", import.meta.url), "utf8")
]);
const generated = `// Generated by scripts/generate-consumer-assets.mjs. Do not edit by hand.
export const GENERATED_DOCS_SKILL = ${JSON.stringify(skillV1)};
export const GENERATED_DOCS_SKILL_V2 = ${JSON.stringify(skillV2)};
export const GENERATED_PRIOR_DOCS_SKILL_V2 = ${JSON.stringify(priorSkillV2)};
export const GENERATED_CALLER_WORKFLOW_TEMPLATE = ${JSON.stringify(caller)};
export const GENERATED_TRANSITION_CATALOG = ${JSON.stringify(transitionCatalog)};
`;

if (process.argv.includes("--write")) {
  await writeFile(output, generated);
} else if (await readFile(output, "utf8") !== generated) {
  throw new Error(`Generated consumer assets are stale. Run ${join(
    packageRoot.pathname,
    "scripts/generate-consumer-assets.mjs"
  )} --write.`);
}

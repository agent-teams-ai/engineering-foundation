async function createMultiPackageRelease(root, baseRevision) {
  await git(root, "checkout", "--detach", baseRevision);
  await rm(join(root, ".changeset", "alpha.md"));
  const foundation = generatedRelease("1.1.0", ["Unified protocol."]);
  const docs = generatedRelease("1.1.0", ["Unified protocol."]);
  await writeFile(
    join(root, "packages", "engineering-foundation", "package.json"),
    JSON.stringify({ name: packageName, version: "1.1.0" }),
  );
  await writeFile(
    join(root, "packages", "engineering-foundation", "CHANGELOG.md"),
    foundation.changelog,
  );
  await writeFile(
    join(root, "packages", "docs-protocol", "package.json"),
    JSON.stringify({ name: docsPackageName, version: "1.1.0" }),
  );
  await writeFile(
    join(root, "packages", "docs-protocol", "CHANGELOG.md"),
    docs.changelog.replace("# " + packageName, "# " + docsPackageName),
  );
  await git(root, "add", ".");
  await git(root, "commit", "-m", "release packages");
  return {
    body:
      "Generated by Changesets.\n\n# Releases\n" +
      foundation.body.slice(foundation.body.indexOf("## ")) +
      "\n\n" +
      docs.body
        .slice(docs.body.indexOf("## "))
        .replace(packageName + "@1.1.0", docsPackageName + "@1.1.0"),
    head: await git(root, "rev-parse", "HEAD"),
  };
}

async function createRelease(
  root,
  baseRevision,
  version,
  summaries,
  { prereleaseChangesets = [] } = {},
) {
  await git(root, "checkout", "--detach", baseRevision);
  for (const id of ["alpha", "beta"]) {
    if (!prereleaseChangesets.includes(id)) {
      await rm(join(root, ".changeset", id + ".md"), { force: true });
    }
  }
  if (prereleaseChangesets.length > 0) {
    await writeFile(
      join(root, ".changeset", "pre.json"),
      JSON.stringify({ mode: "pre", tag: "rc", changesets: prereleaseChangesets }),
    );
  }
  const generated = generatedRelease(version, summaries);
  await writeFile(
    join(root, "packages", "engineering-foundation", "package.json"),
    JSON.stringify({ name: packageName, version }),
  );
  await writeFile(
    join(root, "packages", "engineering-foundation", "CHANGELOG.md"),
    generated.changelog,
  );
  await git(root, "add", ".");
  await git(root, "commit", "-m", "release " + version);
  return { head: await git(root, "rev-parse", "HEAD"), body: generated.body };
}

async function createPrereleaseExit(root, baseRevision, version, summary) {
  await git(root, "checkout", "--detach", baseRevision);
  await rm(join(root, ".changeset", "pre.json"));
  await rm(join(root, ".changeset", "alpha.md"));
  const baseChangelog = await git(
    root,
    "show",
    baseRevision + ":packages/engineering-foundation/CHANGELOG.md",
  );
  const title = "# " + packageName + "\n\n";
  const section = "## " + version + "\n\n### Minor Changes\n\n- " + summary;
  await writeFile(
    join(root, "packages", "engineering-foundation", "package.json"),
    JSON.stringify({ name: packageName, version }),
  );
  await writeFile(
    join(root, "packages", "engineering-foundation", "CHANGELOG.md"),
    title + section + "\n\n" + baseChangelog.slice(title.length) + "\n",
  );
  await git(root, "add", ".");
  await git(root, "commit", "-m", "exit prerelease");
  return {
    head: await git(root, "rev-parse", "HEAD"),
    body: "# Releases\n" + section.replace("## " + version, "## " + packageName + "@" + version),
  };
}

test("accepts Changesets prerelease consumption recorded in pre.json", async () => {
  const fixture = await createFixture();
  try {
    await git(fixture.root, "checkout", "--detach", fixture.mainA);
    await writeFile(
      join(fixture.root, ".changeset", "pre.json"),
      JSON.stringify({ mode: "pre", tag: "rc", changesets: [] }),
    );
    await git(fixture.root, "add", ".changeset/pre.json");
    await git(fixture.root, "commit", "-m", "enter prerelease mode");
    const prereleaseMain = await git(fixture.root, "rev-parse", "HEAD");
    const release = await createRelease(
      fixture.root,
      prereleaseMain,
      "1.1.0-rc.0",
      ["Alpha package change."],
      { prereleaseChangesets: ["alpha"] },
    );

    assert.deepEqual(
      await violations(
        fixture.root,
        prereleaseMain,
        prereleaseMain,
        release,
        release.head,
      ),
      [],
    );
  } finally {
    await rm(fixture.root, { recursive: true, force: true });
  }
});

test("accepts only an exact stable release when processed main exits prerelease", async () => {
  const fixture = await createFixture();
  try {
    await git(fixture.root, "checkout", "--detach", fixture.mainA);
    await writeFile(
      join(fixture.root, ".changeset", "pre.json"),
      JSON.stringify({
        mode: "exit",
        tag: "rc",
        initialVersions: { [packageName]: "1.0.0" },
        changesets: ["alpha"],
      }),
    );
    await writeFile(
      join(fixture.root, "packages", "engineering-foundation", "package.json"),
      JSON.stringify({ name: packageName, version: "1.1.0-rc.0" }),
    );
    await writeFile(
      join(fixture.root, "packages", "engineering-foundation", "CHANGELOG.md"),
      "# " + packageName + "\n\n## 1.1.0-rc.0\n\nAlpha package change.\n\n## 1.0.0\n",
    );
    await git(fixture.root, "add", ".");
    await git(fixture.root, "commit", "-m", "prepare prerelease exit");
    const exitMain = await git(fixture.root, "rev-parse", "HEAD");
    const release = await createPrereleaseExit(
      fixture.root,
      exitMain,
      "1.1.0",
      "Alpha package change.",
    );

    assert.deepEqual(
      await violations(fixture.root, exitMain, exitMain, release, release.head),
      [],
    );

    const wrongVersion = await createPrereleaseExit(
      fixture.root,
      exitMain,
      "1.1.1",
      "Alpha package change.",
    );
    assert.match(
      (
        await violations(
          fixture.root,
          exitMain,
          exitMain,
          wrongVersion,
          wrongVersion.head,
        )
      ).join("\n"),
      /exact stable version/u,
    );
  } finally {
    await rm(fixture.root, { recursive: true, force: true });
  }
});

